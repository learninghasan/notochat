"""Verified identity gateway and physically isolated business workspaces.

Production: PostgreSQL schema per organization. Development: SQLite file per org.
Run `uvicorn server:app`, not the legacy-only `main:app`, for account mode.
"""
import asyncio
import base64
import hashlib
import hmac
import json
import os
import re
import threading
import time
import uuid
from collections import OrderedDict
from pathlib import Path

from sqlalchemy import MetaData, Table, Column, String, Float, create_engine, insert, delete, select, text
from sqlalchemy.exc import IntegrityError
from starlette.requests import Request
from starlette.responses import JSONResponse

from main import app as legacy_app, engine as registry_engine, create_workspace

metadata=MetaData()
registry=Table('notochat_business_registry',metadata,Column('organization_id',String(200),primary_key=True),Column('namespace',String(80),unique=True,nullable=False))
audit=Table('notochat_audit_events',metadata,Column('id',String(40),primary_key=True),Column('organization_id',String(200),index=True),Column('user_id',String(200)),Column('method',String(10)),Column('path',String(500)),Column('status',String(10)),Column('created_at',Float))
nonces=Table('notochat_identity_nonces',metadata,Column('nonce',String(100),primary_key=True),Column('expires_at',Float,nullable=False))


class BusinessGateway:
    def __init__(self,legacy,engine,factory,secret=None,sqlite_dir=None):
        self.legacy=legacy;self.engine=engine;self.factory=factory;self.secret=secret
        self.sqlite_dir=Path(sqlite_dir or os.getenv('TENANT_SQLITE_DIR','./tenant-data'))
        self.cache=OrderedDict();self.lock=threading.RLock()
        metadata.create_all(engine)

    def verify(self,headers,method,path,body):
        secret=self.secret or os.getenv('INTERNAL_API_SECRET','')
        if len(secret)<32:raise ValueError('Business API trust is not configured')
        encoded=headers.get('x-notochat-identity','');signature=headers.get('x-notochat-signature','')
        if not encoded or len(encoded)>6000:raise PermissionError('Verified business identity required')
        expected=hmac.new(secret.encode(),encoded.encode(),hashlib.sha256).hexdigest()
        if not hmac.compare_digest(signature,expected):raise PermissionError('Invalid business identity signature')
        try:p=json.loads(base64.urlsafe_b64decode(encoded+'='*(-len(encoded)%4)))
        except (ValueError,TypeError):raise PermissionError('Invalid identity payload')
        if not isinstance(p,dict):raise PermissionError('Invalid identity payload')
        if abs(time.time()-p.get('timestamp',0))>30:raise PermissionError('Business identity expired')
        if p.get('method')!=method or p.get('path')!=path or p.get('body_sha256')!=hashlib.sha256(body).hexdigest():raise PermissionError('Request identity binding failed')
        if p.get('role') not in ('owner','admin','member'):raise PermissionError('Unsupported business role')
        for key in ('user_id','organization_id','nonce'):
            if not isinstance(p.get(key),str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,200}',p[key]):raise PermissionError('Invalid identity field')
        # Persisted unique nonces prevent replay across processes or restarts.
        try:
            with self.engine.begin() as c:
                c.execute(delete(nonces).where(nonces.c.expires_at<time.time()))
                c.execute(insert(nonces).values(nonce=p['nonce'],expires_at=time.time()+60))
        except IntegrityError:raise PermissionError('Identity proof was already used')
        return p

    def workspace(self,organization_id):
        with self.lock:
            if organization_id in self.cache:
                self.cache.move_to_end(organization_id);return self.cache[organization_id]
            namespace='business_'+hashlib.sha256(organization_id.encode()).hexdigest()[:32]
            with self.engine.begin() as connection:
                row=connection.execute(select(registry).where(registry.c.organization_id==organization_id)).first()
                if row:namespace=row.namespace
                else:
                    try:
                        with connection.begin_nested():connection.execute(insert(registry).values(organization_id=organization_id,namespace=namespace))
                    except IntegrityError:pass  # Another gateway registered the same deterministic namespace.
            if self.engine.dialect.name=='postgresql':
                # Namespace is generated by the server, never supplied as SQL by a caller.
                if not re.fullmatch(r'business_[a-f0-9]{32}',namespace):raise ValueError('Invalid stored business namespace')
                with self.engine.begin() as c:c.execute(text(f'CREATE SCHEMA IF NOT EXISTS "{namespace}"'))
                tenant_engine=self.engine.execution_options(schema_translate_map={None:namespace})
            elif self.engine.dialect.name=='sqlite':
                self.sqlite_dir.mkdir(mode=0o700,parents=True,exist_ok=True)
                tenant_engine=create_engine('sqlite:///'+str(self.sqlite_dir/ (namespace+'.db')))
            else:raise ValueError('Business isolation requires PostgreSQL or development SQLite')
            app=self.factory(tenant_engine,trusted_identity=True,seed_sample=False)
            if self.engine.dialect.name=='sqlite':
                (self.sqlite_dir/(namespace+'.db')).chmod(0o600)
            def read_audit():
                with self.engine.connect() as connection:
                    return [dict(row) for row in connection.execute(select(audit).where(audit.c.organization_id==organization_id).order_by(audit.c.created_at.desc()).limit(100)).mappings()]
            app.state.audit_events=read_audit
            self.cache[organization_id]=app
            if len(self.cache)>32:self.cache.popitem(last=False)
            return app

    async def __call__(self,scope,receive,send):
        if scope['type']!='http':return await self.legacy(scope,receive,send)
        request=Request(scope,receive=receive)
        headers=request.headers
        public=re.fullmatch(r'/business/([A-Za-z0-9_-]{1,200})(/webhooks/(?:meta|courier)|/widget(?:/sessions|/messages)?|/payments/(?:ipn|return))',scope['path'])
        if public:
            organization_id,child_path=public.groups()
            with self.engine.connect() as c:known=c.execute(select(registry.c.organization_id).where(registry.c.organization_id==organization_id)).first()
            if not known:return await JSONResponse({'detail':'Business not found'},status_code=404)(scope,receive,send)
            try:child=await asyncio.to_thread(self.workspace,organization_id)
            except Exception:return await JSONResponse({'detail':'Business connection unavailable'},status_code=503)(scope,receive,send)
            child_scope={**scope,'path':child_path,'raw_path':child_path.encode()}
            return await child(child_scope,receive,send)
        if not headers.get('x-notochat-identity'):
            # Legacy access remains separate; cookies alone never grant access here.
            return await self.legacy(scope,receive,send)
        body=await request.body()
        if len(body)>12_500_000:return await JSONResponse({'detail':'Request too large'},status_code=413)(scope,receive,send)
        path=scope['path']+('?' + scope['query_string'].decode() if scope.get('query_string') else '')
        try:
            principal=await asyncio.to_thread(self.verify,headers,scope['method'],path,body)
            child=await asyncio.to_thread(self.workspace,principal['organization_id'])
        except PermissionError as e:return await JSONResponse({'detail':str(e)},status_code=401)(scope,receive,send)
        except ValueError as e:return await JSONResponse({'detail':str(e)},status_code=503)(scope,receive,send)
        except Exception:return await JSONResponse({'detail':'Business workspace could not be initialized'},status_code=503)(scope,receive,send)
        child_scope={**scope,'notochat.principal':principal}
        consumed=False
        async def buffered_receive():
            nonlocal consumed
            if not consumed:consumed=True;return {'type':'http.request','body':body,'more_body':False}
            return await receive()
        status=[500]
        async def observed_send(message):
            if message['type']=='http.response.start':status[0]=message['status']
            await send(message)
        await child(child_scope,buffered_receive,observed_send)
        if (scope['method'] not in ('GET','HEAD') or scope['path']=='/workspace/export') and 200<=status[0]<300:
            def record_audit():
                with self.engine.begin() as connection:connection.execute(insert(audit).values(id=uuid.uuid4().hex,organization_id=principal['organization_id'],user_id=principal['user_id'],method=scope['method'],path=scope['path'][:500],status=str(status[0]),created_at=time.time()))
            try:await asyncio.to_thread(record_audit)
            except Exception:pass  # A failed audit sink must not repeat an already-committed mutation.



app=BusinessGateway(legacy_app,registry_engine,create_workspace)
